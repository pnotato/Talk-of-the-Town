// Command gentypes writes the TypeScript types for the RunLog contract
// from the Go structs in internal/sim. Run it with `make types`.
//
// Mapping (field names come from json tags; `json:"-"` and unexported fields are skipped):
//
//	int*, uint*, float*  -> number
//	string, bool         -> string, boolean
//	[]T, [N]T            -> T[]
//	struct               -> export interface, emitted once, in first-seen order
//	enum string type     -> string-literal union of its registered values
//
// Anything else is an error, so a new field kind can't slip through silently.
package main

import (
	"fmt"
	"os"
	"reflect"
	"strings"

	"talkofthetown/internal/sim"
)

// printWidth matches .prettierrc.json so the output is prettier-clean.
const printWidth = 100

const header = "// Code generated by cmd/gentypes. DO NOT EDIT.\n// Source: internal/sim. Regenerate with `make types`.\n"

// roots are the top-level types the client receives. Nested structs are found by reflection.
var roots = []reflect.Type{
	reflect.TypeFor[sim.Town](),
	reflect.TypeFor[sim.RunLog](),
}

type enum struct {
	t      reflect.Type
	values []string
}

// enums lists each named string type and its values, since reflect can't see constants.
var enums = []enum{
	{reflect.TypeFor[sim.Shape](), strs(sim.Shapes[:])},
	{reflect.TypeFor[sim.Trait](), strs([]sim.Trait{
		sim.TraitSkeptic, sim.TraitGullible, sim.TraitQuiet, sim.TraitChatty,
		sim.TraitUnconvincing, sim.TraitCharismatic,
		sim.TraitFamilyOriented, sim.TraitRecluse, sim.TraitLeader,
	})},
}

func strs[T ~string](xs []T) []string {
	out := make([]string, len(xs))
	for i, x := range xs {
		out[i] = string(x)
	}
	return out
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gentypes <out.ts>")
		os.Exit(2)
	}
	src, err := generate(roots, enums)
	if err == nil {
		err = os.WriteFile(os.Args[1], []byte(src), 0o644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "gentypes:", err)
		os.Exit(1)
	}
}

// generate returns the .ts source. Output is formatted the way prettier would.
func generate(roots []reflect.Type, enums []enum) (string, error) {
	var b strings.Builder
	b.WriteString(header)
	known := map[reflect.Type]bool{}
	for _, e := range enums {
		known[e.t] = true
		quoted := make([]string, len(e.values))
		for i, v := range e.values {
			quoted[i] = fmt.Sprintf("%q", v)
		}
		line := fmt.Sprintf("export type %s = %s;", e.t.Name(), strings.Join(quoted, " | "))
		if len(line) > printWidth {
			line = fmt.Sprintf("export type %s =\n  | %s;", e.t.Name(), strings.Join(quoted, "\n  | "))
		}
		b.WriteString("\n" + line + "\n")
	}

	queue := append([]reflect.Type(nil), roots...)
	seen := map[reflect.Type]bool{}
	for len(queue) > 0 {
		t := queue[0]
		queue = queue[1:]
		if seen[t] {
			continue
		}
		seen[t] = true
		fmt.Fprintf(&b, "\nexport interface %s {\n", t.Name())
		for f := range t.Fields() {
			name := f.Name
			if tag, _, _ := strings.Cut(f.Tag.Get("json"), ","); tag == "-" || !f.IsExported() {
				continue
			} else if tag != "" {
				name = tag
			}
			ts, err := tsType(f.Type, known, &queue)
			if err != nil {
				return "", fmt.Errorf("%s.%s: %w", t.Name(), f.Name, err)
			}
			fmt.Fprintf(&b, "  %s: %s;\n", name, ts)
		}
		b.WriteString("}\n")
	}
	return b.String(), nil
}

func tsType(t reflect.Type, known map[reflect.Type]bool, queue *[]reflect.Type) (string, error) {
	if known[t] {
		return t.Name(), nil
	}
	switch t.Kind() {
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.String:
		if t.Name() != "string" {
			return "", fmt.Errorf("named string type %s has no enum entry", t)
		}
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Slice, reflect.Array:
		el, err := tsType(t.Elem(), known, queue)
		return el + "[]", err
	case reflect.Struct:
		*queue = append(*queue, t)
		return t.Name(), nil
	}
	return "", fmt.Errorf("unsupported kind %s", t.Kind())
}
